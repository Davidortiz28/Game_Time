CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    launcher VARCHAR(40) NOT NULL,
    executable_path TEXT NOT NULL,
    launch_arguments TEXT,
    category VARCHAR(100),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT games_name_launcher_unique UNIQUE (name, launcher)
);

CREATE TABLE play_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    duration_seconds INTEGER NOT NULL CHECK (duration_seconds > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    grace_until TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    interrupted_at TIMESTAMPTZ,
    end_reason VARCHAR(40),
    CONSTRAINT play_sessions_status_check
        CHECK (status IN ('CREATED', 'ACTIVE', 'GRACE', 'COMPLETED', 'ADMIN_ENDED', 'INTERRUPTED')),
    CONSTRAINT play_sessions_timer_fields_check
        CHECK (
            (status = 'CREATED' AND started_at IS NULL AND expires_at IS NULL)
            OR (status <> 'CREATED' AND started_at IS NOT NULL AND expires_at IS NOT NULL)
        )
);

CREATE INDEX play_sessions_status_created_idx ON play_sessions (status, created_at DESC);
CREATE INDEX play_sessions_expires_at_idx ON play_sessions (expires_at) WHERE status IN ('ACTIVE', 'GRACE');

CREATE TABLE session_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING',
    decided_at TIMESTAMPTZ,
    decision_note VARCHAR(500),
    created_session_id UUID REFERENCES play_sessions(id),
    CONSTRAINT session_requests_status_check
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT session_requests_decision_check
        CHECK (
            (status = 'PENDING' AND decided_at IS NULL)
            OR (status <> 'PENDING' AND decided_at IS NOT NULL)
        ),
    CONSTRAINT session_requests_approved_session_check
        CHECK (status <> 'APPROVED' OR created_session_id IS NOT NULL)
);

CREATE INDEX session_requests_status_requested_idx ON session_requests (status, requested_at);
