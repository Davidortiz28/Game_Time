CREATE TABLE export_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING',
    decided_at TIMESTAMPTZ,
    decision_note VARCHAR(500),
    CONSTRAINT export_requests_status_check CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    CONSTRAINT export_requests_decision_check CHECK (
        (status = 'PENDING' AND decided_at IS NULL)
        OR (status <> 'PENDING' AND decided_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX export_requests_single_pending_idx
    ON export_requests ((TRUE)) WHERE status = 'PENDING';
