-- Biblioteca: descripción para la futura categorización con IA y nombre del proceso
-- que el cliente supervisa y al que solicita el cierre normal.
ALTER TABLE games
    ADD COLUMN description TEXT,
    ADD COLUMN process_name VARCHAR(260);

ALTER TABLE games
    ADD CONSTRAINT games_launcher_check CHECK (launcher IN ('STEAM', 'EPIC', 'OTHER'));

-- Sesiones: CANCELLED permite descartar una sesión creada que nunca se inició.
-- last_heartbeat_at registra el último contacto del cliente del jugador.
ALTER TABLE play_sessions ADD COLUMN last_heartbeat_at TIMESTAMPTZ;

ALTER TABLE play_sessions DROP CONSTRAINT play_sessions_status_check;
ALTER TABLE play_sessions
    ADD CONSTRAINT play_sessions_status_check
        CHECK (status IN ('CREATED', 'ACTIVE', 'GRACE', 'COMPLETED', 'ADMIN_ENDED', 'INTERRUPTED', 'CANCELLED'));

ALTER TABLE play_sessions DROP CONSTRAINT play_sessions_timer_fields_check;
ALTER TABLE play_sessions
    ADD CONSTRAINT play_sessions_timer_fields_check
        CHECK (
            (status IN ('CREATED', 'CANCELLED') AND started_at IS NULL AND expires_at IS NULL)
            OR (status NOT IN ('CREATED', 'CANCELLED') AND started_at IS NOT NULL AND expires_at IS NOT NULL)
        );

-- Solo puede existir una sesión abierta (creada, activa o en gracia) a la vez.
CREATE UNIQUE INDEX play_sessions_single_open_idx
    ON play_sessions ((TRUE))
    WHERE status IN ('CREATED', 'ACTIVE', 'GRACE');

-- Solo puede existir una solicitud pendiente a la vez.
CREATE UNIQUE INDEX session_requests_single_pending_idx
    ON session_requests ((TRUE))
    WHERE status = 'PENDING';

-- Juegos iniciados desde el launcher de GameTime durante una sesión.
CREATE TABLE game_launches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES play_sessions(id) ON DELETE CASCADE,
    game_id BIGINT REFERENCES games(id) ON DELETE SET NULL,
    game_name VARCHAR(200) NOT NULL,
    launched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    outcome VARCHAR(30),
    CONSTRAINT game_launches_outcome_check
        CHECK (outcome IS NULL OR outcome IN ('EXITED', 'CLOSED_NORMALLY', 'IGNORED_CLOSE', 'LAUNCH_FAILED'))
);

CREATE INDEX game_launches_session_idx ON game_launches (session_id, launched_at);
